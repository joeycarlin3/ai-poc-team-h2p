        "\n",
        "def transcribe_audio_bytes(audio_bytes: bytes, mime_type: str = \"audio/wav\") -> Optional[str]:\n",
        "    \"\"\"\n",
        "    Send inline audio bytes to Gemini via generate_content with a Part.from_bytes.\n",
        "    Works for files < ~20MB (for larger files use cloud storage + file reference).\n",
        "    Returns transcript text or None on error.\n",
        "    \"\"\"\n",
        "    try:\n",
        "        # Build a user prompt asking for a transcription with light formatting.\n",
        "        user_prompt = (\n",
        "            \"Please transcribe the attached audio. Provide a clean transcription. \"\n",
        "            \"If possible, add short timecodes (mm:ss) every ~20 seconds and label the speaker as 'Candidate'.\"\n",
        "        )\n",
        "\n",
        "        audio_part = types.Part.from_bytes(data=audio_bytes, mime_type=mime_type)\n",
