        "def parse_data_url_or_bytes(audio_obj) -> Optional[bytes]:\n",
        "    \"\"\"\n",
        "    The streamlit mic recorder returns different shapes depending on versions:\n",
        "      - sometimes a dict with 'data' or 'blob' or 'file' containing a data:audio/...;base64,... string\n",
        "      - sometimes raw bytes\n",
        "    This helper attempts to extract raw bytes.\n",
        "    \"\"\"\n",
        "    if audio_obj is None:\n",
        "        return None\n",
        "\n",
        "    # If it's a dict with a data URL:\n",
        "    if isinstance(audio_obj, dict):\n",
        "        # common keys: 'data', 'file', 'blob', 'bytes'\n",
        "        for key in (\"data\", \"file\", \"blob\", \"bytes\", \"wav_bytes\"):\n",
        "            if key in audio_obj and audio_obj[key]:\n",
        "                val = audio_obj[key]\n",
        "                # If bytes already\n",
        "                if isinstance(val, (bytes, bytearray)):\n",
        "                    return bytes(val)\n",
        "                # If it's a data URL string:\n",
        "                if isinstance(val, str) and val.startswith(\"data:audio\"):\n",
        "                    try:\n",
        "                        header, b64 = val.split(\",\", 1)\n",
        "                        return base64.b64decode(b64)\n",
        "                    except Exception:\n",
        "                        # If it's plain base64 without header\n",
        "                        try:\n",
        "                            return base64.b64decode(val)\n",
        "                        except Exception:\n",
        "                            return None\n",
        "                # If it's a plain base64 string:\n",
        "                if isinstance(val, str):\n",
        "                    try:\n",
        "                        return base64.b64decode(val)\n",
        "                    except Exception:\n",
        "                        continue\n",
        "\n",
        "    # If it's raw bytes\n",
        "    if isinstance(audio_obj, (bytes, bytearray)):\n",
        "        return bytes(audio_obj)\n",
        "\n",
        "    # If it's a string that might be a data URL\n",
        "    if isinstance(audio_obj, str) and audio_obj.startswith(\"data:audio\"):\n",
        "        try:\n",
        "            _, b64 = audio_obj.split(\",\", 1)\n",
        "            return base64.b64decode(b64)\n",
        "        except Exception:\n",
        "            return None\n",
