        "    try:\n",
        "        resp = client.models.generate_content(model=MODEL, contents=[prompt])\n",
        "        # Most SDK responses expose .text — fallback to parsing candidates if needed\n",
        "        if hasattr(resp, \"text\") and resp.text:\n",
        "            return resp.text.strip()\n",
        "        # Best-effort parsing if the SDK returns a more detailed object\n",
        "        try:\n",
        "            # Some responses include candidates -> content parts\n",
        "            return resp.candidates[0].content[0].text.strip()\n",
        "        except Exception:\n",
        "            return \"Tell me about a time you had to manage a difficult stakeholder.\"\n",
